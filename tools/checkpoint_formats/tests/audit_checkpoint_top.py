"""Independent immutable-input, execution, cut and native-DCP fixture audit.

Audits the exact inputs used by each execution, without requiring a mutable
elaboration directory to retain byte-identical output forever. A new elaboration
is a new execution; VCS and synthesis must still agree on every generated byte.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import socket
import tempfile
import zipfile

from tools.checkpoint_formats.codec import require
from tools.checkpoint_formats.fpga_transport import decode_frames, encode_transport_semantic
from tools.checkpoint_formats.tests.verify_checkpoint_top_vcs import GENERATED, SOURCES

ROOT = Path(__file__).resolve().parents[3]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def audit(top_path, synthesis_path, inventory_path, current=True):
    top = json.loads(top_path.read_text())
    native = json.loads(synthesis_path.read_text())
    require(top['status'] == native['status'] == 'pass' and top['backend'] == 'eda' and native['backend'] == 'f2',
            'missing successful execution')
    require(not any(top[k] for k in ('physical_fpga_validated', 'rocket_image_integrated', 'complete_runtime_ownership'))
            and not native['physical_fpga_capture'] and not native['full_rocket_image_build'], 'fixture scope changed')
    require(set(top['sources']) == set(SOURCES) and set(top['generated']) == set(GENERATED), 'incomplete source inventory')
    files = 0

    def check_file(path, digest, allow_empty=False):
        nonlocal files
        require(path.is_file() and (path.stat().st_size > 0 or allow_empty) and sha(path) == digest,
                f'file integrity: {path}')
        files += 1

    for name, digest in top['sources'].items():
        check_file(top_path.parent / 'source-snapshots' / name, digest)
        if current:
            check_file(ROOT / name, digest)
    require(native['generated'] == top['generated'], 'VCS and native synthesis generated inputs differ')
    for name, digest in top['generated'].items():
        check_file(top_path.parent / 'generated-snapshots' / name, digest)
        check_file(synthesis_path.parent / 'generated-snapshots' / name, digest)
    for name, digest in top['artifacts'].items():
        require(Path(name).name == name, 'invalid top artifact path')
        # Successful quiet C++ compiles and VCS's unused UCLI command file can
        # be empty. Their exact bytes still bind; required execution markers,
        # waveforms, captures and source inputs must all be nonempty below.
        check_file(top_path.parent / name, digest,
                   allow_empty=name in ('host-build.log', 'constructor-build.log', 'ucli.key'))
    for name, digest in native['artifacts'].items():
        require(Path(name).name == name, 'invalid native artifact path')
        check_file(synthesis_path.parent / name, digest)
    if current:
        require(sha(synthesis_path.parent / 'capture_top_synth.tcl') ==
                sha(ROOT / 'tools/checkpoint_formats/capture_top_synth.tcl'), 'stale synthesis script')
    require(top['checks'] == 7858 and top['dma_stalls'] == 660 and top['frozen_edges'] == 1926,
            'incomplete top stress')
    for row in top['commands']:
        log = top_path.parent / Path(row['log']).name
        require(log.is_file(), 'execution log missing')
        expected = 1 if log.name == 'semantic-corruption.log' else 0
        require(row['returncode'] == expected, 'unexpected command status')
    require('-full64' in top['commands'][0]['argv'] and '-debug_access+all' in top['commands'][0]['argv'] and
            any('Y-2026.03-SP2/bin/vcs' in a for a in top['commands'][0]['argv']), 'wrong VCS toolchain')
    compile_command = top['commands'][0]
    for name in ('FPGATop.v', 'generated-bank.sv', 'CheckpointCaptureTransport.sv', 'CheckpointCaptureCut.sv'):
        require(str(Path(compile_command['cwd']) / 'generated-snapshots' / name) in compile_command['argv'],
                'VCS did not compile its private input snapshot')
    host_build = next(c for c in top['commands'] if c['log'].endswith('/host-build.log'))
    require('-fsanitize=address,undefined' in host_build['argv'], 'sanitizer scope was reduced')
    require('CHECKPOINT_TOP_PASS checks=7858 captures=3 dma_stalls=660 frozen_edges=1926' in
            (top_path.parent / 'run.log').read_text(), 'execution marker absent')
    snapshots = top_path.parent / 'generated-snapshots'
    manifest = json.loads((snapshots / 'generated-bank-semantic.json').read_text())
    binding = json.loads((top_path.parent / 'binding.json').read_text())
    require([c['target_cycle'] for c in top['captures']] == [109, 167, 305], 'missing cut')
    for cut in top['captures']:
        index = cut['index']; frames = top_path.parent / f'capture-{index}.frames'
        image = top_path.parent / f'capture-{index}.rtlckpt'
        check_file(frames, cut['frames_sha256']); check_file(image, cut['rtlckpt_sha256'])
        require(len(decode_frames(frames.read_bytes(), manifest, binding, cut['target_cycle'])) == cut['words'] == 33,
                'incomplete frame state')
        require(image.read_bytes() == encode_transport_semantic(frames.read_bytes(), manifest, binding,
                'FPGATop-fixture-VCS-only', cut['target_cycle']), 'semantic container does not match transport')
        require(cut['decoder_negatives'] == 66 and cut['host_sanitizer_checks'] == 5532 and
                'CHECKPOINT_CAPTURE_HOST_PASS checks=5532' in
                (top_path.parent / f'host-cut{index}.log').read_text(), 'missing negative/sanitizer checks')
    require('TOP_FAIL functional-input state oracle target_cycle=109 freeze=1 frame=1' in
            (top_path.parent / 'semantic-corruption.log').read_text(), 'first-divergence check missing')
    require(not list((top_path.parent / 'semantic-corruption').glob('*.rtlckpt')), 'corrupt capture published')
    require((top_path.parent / 'top.vcd').stat().st_size > 1000, 'waveform missing')
    require(native['command']['returncode'] == 0 and 'CHECKPOINT_TOP_SYNTH_PASS' in
            (synthesis_path.parent / 'command.log').read_text(), 'native synthesis incomplete')
    require(native['command']['argv'][-2:] ==
            [str(Path(native['command']['cwd']) / 'generated-snapshots'), native['command']['cwd']],
            'Vivado did not use its private input snapshot')
    with zipfile.ZipFile(synthesis_path.parent / 'FPGATop.dcp') as dcp:
        require(dcp.testzip() is None, 'native DCP CRC failure')
        metadata = dcp.read('dcp.xml').decode()
        for text in ('<Part Name="xcvu47p-fsvh2892-2-e"', '<Top Name="FPGATop"',
                     '<OutOfContext Name="1"', 'Vivado v2025.2'):
            require(text in metadata, 'native DCP identity: ' + text)
        require(len(dcp.read('FPGATop.edf')) > 0, 'empty native netlist')
    utilization = (synthesis_path.parent / 'utilization.rpt').read_text()
    luts = int(re.search(r'\| CLB LUTs\*\s*\|\s*(\d+)\s*\|', utilization)[1])
    registers = int(re.search(r'\| CLB Registers\s*\|\s*(\d+)\s*\|', utilization)[1])
    require(luts > 0 and registers > 0, 'empty synthesized design')
    inventory = json.loads(inventory_path.read_text())
    require(inventory['instances'] == [] and not inventory['metasimulation_enabled'] and
            inventory['build_execution'] == 'localhost', 'resource inventory mismatch')
    require(not any(Path(p['executable']).name in ('java', 'vivado', 'firesim') for p in
                    inventory['local_build_processes']['processes']), 'local build jobs still running')
    return dict(files_verified=files, cuts=3, luts=luts, registers=registers,
                top_receipt_sha256=sha(top_path), synthesis_receipt_sha256=sha(synthesis_path),
                inventory_sha256=sha(inventory_path))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--top', type=Path, required=True)
    parser.add_argument('--synthesis', type=Path, required=True)
    parser.add_argument('--inventory', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    result = audit(args.top.resolve(), args.synthesis.resolve(), args.inventory.resolve())
    base = args.out.resolve()
    require(base.is_relative_to(ROOT / 'automations/checkpoint_loop/runs'), 'evidence outside runs')
    base.mkdir(parents=True, exist_ok=True)
    out = Path(tempfile.mkdtemp(prefix='top-audit-', dir=base)) / 'audit.json'
    out.write_text(json.dumps(dict(status='pass', backend='eda', original_root=str(ROOT),
        host=socket.gethostname(), observed_utc=datetime.now(timezone.utc).isoformat(),
        physical_fpga_capture=False, scope='immutable execution, per-cut, native DCP and resource fixture audit',
        **result), indent=2) + '\n')
    print(out)


if __name__ == '__main__':
    main()
