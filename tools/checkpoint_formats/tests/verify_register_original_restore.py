        for n, h in oracle['sources'].items(): require(file_sha(local(ROOT, n)) == h, 'oracle source drift')
        doc['reference_receipt'] = dict(path=str(rr), sha256=file_sha(rr))
        doc['reference_binding'] = dict(path=str(rb), sha256=file_sha(rb))
        doc['reference_audit'] = audit_reference(rb.parent, generated)
        doc['audit'] = audit(generated)
        doc['rejected_mutations'] = original_mutations(generated, out/'mutations')
        b = json.loads((generated/'binding.json').read_text()); bits = b['bits']; root = b['selected_execution'].split('.')[0]
        require(b['snapshot_version'] == 4 and b['staging_restore_supported'], 'explicit original and staging restore required')
