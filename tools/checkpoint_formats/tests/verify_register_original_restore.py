def original_mutations(generated, out):
    """Rehash mutations so the independent reconstruction must detect them."""
    rejected = {}
    for case in ('register-load', 'register-hold', 'register-signed', 'memory-enable',
                 'memory-mask', 'memory-address', 'memory-data', 'memory-clock',
                 'child-hold', 'child-load', 'child-state', 'child-address',
                 'unselected-hold', 'original-ready', 'original-depth', 'original-contract',
                 'original-policy', 'hidden-state', 'effect-enable', 'missing-row', 'aliased-row',
                 'wrong-offset', 'image-admission', 'missing-annotations', 'original-port-width'):
        target = out/case
        shutil.copytree(generated, target)
        b = json.loads((target/'binding.json').read_text())
        text = (target/'instrumented.fir').read_text()
        modules = parse_modules((target/'host.fir').read_text())
        root = b['selected_execution'].split('.')[0]
        before = text
        if case.startswith('register-'):
            rows = [r for r in b['state'] if r.get('kind') != 'memory' and
                    (case != 'register-signed' or r['signed'])]
            if not rows:
                continue
            row = rows[0]
            name = row['hierarchy'].rsplit('.', 1)[1]
            pattern = r'(^    '+re.escape(name)+r' <= )([^\n]+)'
            m = re.search(pattern, text, re.M)
            value = m[2]
            if case == 'register-hold':
                value = value.replace(PREFIX+'original_hold', 'UInt<1>("h0")', 1)
            elif case == 'register-load':
                value = value.replace(PREFIX+'original_load', 'UInt<1>("h1")', 1)
            else:
                value = value.replace('asSInt(bits(', 'asSInt(not(bits(', 1).replace(')), ', '))), ', 1)
            text = text[:m.start(2)]+value+text[m.end(2):]
        elif case.startswith('memory-'):
            pin = case.split('-')[1]
            pin = {'enable': 'en', 'address': 'addr', 'clock': 'clk'}.get(pin, pin)
            row = next(r for r in b['state'] if r.get('kind') == 'memory')
            name = row['hierarchy'].rsplit('.', 1)[1]
            ram = modules[row['module']]
            writer = next(k for k in ram['drivers'] if k.startswith(name+'.') and k.endswith('.mask')).rsplit('.', 1)[0]
            text, count = re.subn(r'(^    '+re.escape(writer+'.'+pin)+r' <= )[^\n]+',
                lambda m: m[1]+('asClock(UInt<1>("h0"))' if pin == 'clk' else 'UInt<1>("h0")'), text, count=1, flags=re.M)
            require(count == 1, 'missing memory mutation')
        elif case.startswith('child-') or case == 'unselected-hold':
            pin = 'original_'+case.split('-')[1]
            matches = list(re.finditer(r'(^    \w+\.'+PREFIX+pin+r' <= )([^\n]+)', text, re.M))
            matches = [m for m in matches if ('UInt<' in m[2]) == (case == 'unselected-hold')]
            if not matches:
                continue
            m = matches[0]
            text = text[:m.start(2)]+('UInt<1>("h1")' if case == 'unselected-hold' else 'UInt<1>("h0")')+text[m.end(2):]
        elif case == 'original-ready':
            text = re.sub(r'(^    '+PREFIX+r'original_ready <= )[^\n]+',
                          lambda m: m[1]+'UInt<1>("h1")', text, count=1, flags=re.M)
        elif case == 'original-depth':
            b['original_restore_depth'] += 1
        elif case == 'original-contract':
            b['original_restore_contract'] = 'release_after_partial_load'
        elif case == 'original-policy':
            b['original_restore_supported'] = False
        elif case == 'missing-row':
            b['state'] = b['state'][:-1]
        elif case == 'aliased-row':
            b['state'][1]['state_id'] = b['state'][0]['state_id']
        elif case == 'wrong-offset':
            b['state'][1]['offset'] += 1
        elif case == 'image-admission':
            b['complete_fpga_capture'] = True
        elif case == 'missing-annotations':
            (target/'instrumented-annotations.json').write_text('[{"class":"unknown"}]\n')
            b['source_annotations_sha256'] = sha('[{"class":"unknown"}]\n')
        elif case == 'original-port-width':
            text = text.replace('input '+PREFIX+'original_state : UInt<'+str(b['bits'])+'>',
                                'input '+PREFIX+'original_state : UInt<'+str(b['bits']-1)+'>', 1)
        elif case == 'hidden-state':
            text = text.replace('    '+OBS+' <= ', '    reg hidden : UInt<1>, clock\n    hidden <= reset\n    '+OBS+' <= ', 1)
        else:
            matches = list(re.finditer(r'and\(not\('+PREFIX+r'original_hold\), ', text))
            if not matches:
                continue
            m = matches[0]
            text = text[:m.start()]+text[m.start():].replace('not('+PREFIX+'original_hold)', 'UInt<1>("h1")', 1)
        require(text != before or case in ('original-depth', 'original-contract', 'original-policy', 'missing-row', 'aliased-row',
            'wrong-offset', 'image-admission', 'missing-annotations'), 'mutation did not change fixture '+case)
        (target/'instrumented.fir').write_text(text)
        b['instrumented_sha256'] = sha(text)
        (target/'binding.json').write_text(json.dumps(b))
        try:
            audit(target)
        except FormatError as e:
            rejected[case] = str(e)
        else:
            raise FormatError('accepted original restore corruption '+case)
    return rejected


def boundary_outputs(generated):
    """Use exactly the selected component boundary, excluding unrelated peers."""
    modules = parse_modules((generated/'host.fir').read_text())
    selected = json.loads((generated/'binding.json').read_text())['selected_execution'].split('.')
    name = selected[0]
    for instance in selected[1:]:
        parent = modules[name]; name = parent['instances'][instance]
        for port, (direction, _) in modules[name]['ports'].items():
            if direction == 'input':
                require(parent['drivers'].get(instance+'.'+port) == port,
                        'fresh component test requires directly mapped original input '+instance+'.'+port)
    require(modules[name]['ports'] == modules[selected[0]]['ports'], 'component and harness boundary shapes differ')
    suffix = '.'.join(selected[1:])
    return {n: (suffix+'.' if suffix else '')+n for n, (d, _) in modules[name]['ports'].items() if d == 'output'}


def donor_bench(generated, cycles=256):
    text = bench(generated)
    modules = parse_modules((generated/'host.fir').read_text())
    b = json.loads((generated/'binding.json').read_text())
    root = b['selected_execution'].split('.')[0]
    ports = list(modules[root]['ports'])
    declarations = 'integer trace_file, trace_count=0; reg trace_active=0;\n'
    outputs = boundary_outputs(generated)
    fields = ','.join('original.'+outputs[n] if n in outputs else n for n in ports)
    emit = ('task trace_edge;if(trace_active && trace_count<'+str(cycles)+')begin\n'
            '$fwrite(trace_file,"'+' '.join(['%h']*len(ports))+'\\n",'+fields+');trace_count++;end endtask\n')
    text = text.replace('task tick;', declarations+emit+'task tick;', 1)
    text = text.replace('clock=1;#3;compare();', 'trace_edge();clock=1;#3;compare();', 1)
    # The capture samples ORIGINAL state before its accepting raw edge. Trace
    # input/output row zero describes exactly that same functional edge.
    marker = 'check(!$isunknown(expected),"all_original_state_initialized");tick();'
    replacement = ('check(!$isunknown(expected),"all_original_state_initialized");'
        'if(label==100)begin donor_file=$fopen("original.hex","w");'
        '$fwrite(donor_file,"%h\\n",expected);$fclose(donor_file);'
        'trace_file=$fopen("boundary.trace","w");check(trace_file!=0,"trace_open");trace_active=1;end tick();')
    require(marker in text, 'donor bench boundary changed')
    text = text.replace(marker, replacement, 1)
    text = text.replace('$display("REGISTER_SNAPSHOT_PASS',
        f'check(trace_count=={cycles},"complete_continuation_trace");$fclose(trace_file);$display("REGISTER_SNAPSHOT_PASS', 1)
    return text


def destination_bench(generated, cycles=256):
    b = json.loads((generated/'binding.json').read_text())
    actual = parse_modules((generated/'instrumented.fir').read_text())
    root = b['selected_execution'].split('.')[0]
    original = parse_modules((generated/'host.fir').read_text())[root]
    bits, depth = b['bits'], b['original_restore_depth']
    lines = ['`timescale 1ns/1ps', 'module original_restore_tb;',
             'import "DPI-C" function void checkpoint_widget_failed();',
             'integer acknowledged_edges=0,raw_edges=0,checks=0,fd,count,corrupt_cycle=-1,skip_address=-1;',
             'reg corrupt_state=0;', f'reg [{bits-1}:0] donor[0:0];', f'reg [{bits+70}:0] staging[0:0];']
    for name, (direction, kind) in actual[root]['ports'].items():
        width = 1 if kind == 'Clock' else int(re.fullmatch(r'UInt<(\d+)>', kind)[1])
        shape = '' if width == 1 else f'[{width-1}:0] '
        initial = name in ('reset', PREFIX+'original_hold', PREFIX+'restore_hold', PREFIX+'owners_present', PREFIX+'functional_frozen')
        lines.append(f'{"reg" if direction == "input" else "wire"} {shape}{name}'+
                     (f'={width}\'d{int(initial)};' if direction == 'input' else ';'))
        if direction == 'output' and name in original['ports']:
            lines.append('reg '+shape+'expected_'+name+';')
    for i, row in enumerate(b['state']):
        hierarchy = 'dut.'+row['hierarchy'].split('.', 1)[1]
        values = [hierarchy+f'[{j}]' for j in reversed(range(row['depth']))] if row.get('kind') == 'memory' else [hierarchy]
        expression = '{'+','.join(values)+'}'
        lines.append(f'wire [{row["width"]-1}:0] original_debug_{i}={expression};')
    lines += [f'{root} dut(.*);', 'task check(input bit okay,input string signal);checks++;if(!okay)begin',
        '$display("ORIGINAL_RESTORE_DIVERGENCE cycle=%0d raw_edges=%0d acknowledged_edges=%0d signal=%s",acknowledged_edges,raw_edges,acknowledged_edges,signal);',
        '$dumpflush;#0.001;checkpoint_widget_failed();$finish;end endtask',
        'task raw_tick;clock=0;#3;clock=1;raw_edges++;#3;clock=0;#3;endtask',
        'initial begin $dumpfile("original-restore.vcd");$dumpvars(0,original_restore_tb);',
        '$readmemh("original.hex",donor);$readmemh("staging-owner-100.hex",staging);',
        'check(!$isunknown(donor[0])&&!$isunknown(staging[0]),"complete_donor");',
        'corrupt_state=$test$plusargs("corrupt_state");count=$value$plusargs("corrupt_cycle=%d",corrupt_cycle);',
        'count=$value$plusargs("skip_address=%d",skip_address);',
        f'{PREFIX}original_state=donor[0]^({bits}\'(corrupt_state));',
        f'{PREFIX}restore_state=staging[0];{PREFIX}target_cycle=staging[0][{bits+64}:{bits+1}];',
        f'{PREFIX}restore_load=1;{PREFIX}original_load=1;',
        f'for(integer i=0;i<{depth};i++)begin {PREFIX}original_address=i;{PREFIX}original_load=(i!=skip_address);#1;',
        f'check({PREFIX}original_ready&&{PREFIX}restore_ready,"restore_ready");raw_tick();end',
        f'{PREFIX}original_load=0;{PREFIX}restore_load=0;#1;']
    for i, row in enumerate(b['state']):
        name = row['hierarchy'].split('.', 1)[1]
        offset, width = row['offset'], row['width']
        lines.append(f'check(original_debug_{i}===donor[0][{offset+width-1}:{offset}],"state_{name}");')
    lines += [f'check({PREFIX}control_state===staging[0],"complete_staging_owner");',
        'check(acknowledged_edges==0,"zero_functional_edges_before_readback");',
        # Invalid restore addresses must freeze without modifying either owner.
        f'{PREFIX}original_address=32\'hffffffff;{PREFIX}original_load=1;#1;',
        f'check(!{PREFIX}original_ready,"invalid_address_refused");raw_tick();',
        f'check({OBS}===donor[0],"invalid_address_preserves_all_originals");',
        f'{PREFIX}original_load=0;raw_tick();check({OBS}===donor[0],"held_without_load");',
        # Both functional reset and arbitrary functional input toggles while
        # held were present throughout loading; no functional edge is accepted.
        f'{PREFIX}original_hold=0;{PREFIX}original_load=1;{PREFIX}restore_hold=0;reset=0;#1;',
        f'check(!{PREFIX}original_ready,"load_without_hold_refused");',
        '$display("ORIGINAL_ZERO_EDGE_READBACK_PASS bits='+str(bits)+' staging_bits='+str(bits+71)+' raw_edges=%0d",raw_edges);',
        'fd=$fopen("boundary.trace","r");check(fd!=0,"trace_open");',
        f'for(integer cycle=0;cycle<{cycles};cycle++)begin',
        'count=$fscanf(fd,"'+' '.join(['%h']*len(original['ports']))+'\\n",'+','.join(
            ('expected_' if d == 'output' else '')+n for n, (d, _) in original['ports'].items())+');',
        f'check(count=={len(original["ports"])},"complete_trace_row");#2;']
    first_output = next(n for n, (d, _) in original['ports'].items() if d == 'output')
    lines.append(f'if(cycle==corrupt_cycle)expected_{first_output}=expected_{first_output}^1\'b1;')
    for n, (d, _) in original['ports'].items():
        if d == 'output':
            signal = 'dut.'+boundary_outputs(generated)[n]
            lines.append(f'check({signal}===expected_{n},"output_{n}");')
    lines += ['raw_tick();acknowledged_edges++;end',
              f'check(acknowledged_edges=={cycles},"complete_continuation");$fclose(fd);',
              '$display("ORIGINAL_RESTORE_PASS acknowledged_edges=%0d checks=%0d",acknowledged_edges,checks);$finish;end endmodule']
    return '\n'.join(lines)+'\n'


def wave_audit(path, generated, original_hex, corrupt_state=False, divergent_cycle=None, partial=False):
    """Read complete original state and edge acknowledgements from raw VCD."""
    b = json.loads((generated/'binding.json').read_text()); donor = int(original_hex.read_text(), 16)
    wanted = {'clock', 'acknowledged_edges', 'raw_edges', PREFIX+'original_hold', OBS} | {
        'original_debug_'+str(i) for i in range(len(b['state']))}
    scopes, codes, values, rows = [], {}, {}, []
    def save():
        if set(codes) == wanted and all(c in values for c in codes.values()):
            rows.append({n: int(values[c], 2) if re.fullmatch('[01]+', values[c]) else None for n, c in codes.items()})
    for line in path.read_text().splitlines():
        parts = line.split()
        if not parts:
            continue
        if parts[0] == '$scope': scopes.append(parts[2])
        elif parts[0] == '$upscope': scopes.pop()
        elif parts[0] == '$var' and scopes == ['original_restore_tb'] and parts[4] in wanted: codes[parts[4]] = parts[3]
        elif line.startswith('#'): save()
        elif line.startswith('b') and len(parts) == 2: values[parts[1]] = parts[0][1:]
        elif line[0] in '01xz': values[line[1:]] = line[0]
    save()
    require(rows and set(codes) == wanted, 'missing original debug-wave signals')
    complete = [r for r in rows if r['raw_edges'] == b['original_restore_depth'] and r['clock'] == 0 and
                r[PREFIX+'original_hold'] == 1 and r['acknowledged_edges'] == 0]
    require(complete, 'missing complete restore-edge waveform observation')
    require((complete[-1][OBS] is None or complete[-1][OBS] != donor) if partial else
            complete[-1][OBS] == donor ^ int(corrupt_state), 'complete zero-edge original waveform readback failed')
    direct = complete[-1]
    expected_donor = donor ^ int(corrupt_state)
    mismatches = []
    for i, row in enumerate(b['state']):
        value = direct['original_debug_'+str(i)]
        expected_bits = (expected_donor >> row['offset']) & ((1 << row['width'])-1)
        if value != expected_bits:
            mismatches.append(row['hierarchy'])
    require(bool(mismatches) if partial else not mismatches,
            'independent original register/memory waveform readback failed')
    expected = 0 if corrupt_state or partial else divergent_cycle if divergent_cycle is not None else 256
    require(rows[-1]['acknowledged_edges'] == expected, 'wave acknowledged divergent functional edge')
    return dict(status='pass', original_bits=b['bits'], independent_original_fields=len(b['state']),
                partial_load_mismatches=mismatches, restore_raw_edges=b['original_restore_depth'],
                acknowledged_edges=expected, corruption_rejected=corrupt_state or partial or divergent_cycle is not None)


