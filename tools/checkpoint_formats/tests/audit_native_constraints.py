"""Reconstruct native wrapper XDC from original constraints and concrete targets."""
import json
from pathlib import Path
import re

from tools.checkpoint_formats.codec import require
from tools.checkpoint_formats.tests.audit_physical_clock_plan import parse_modules
from tools.checkpoint_formats.tests.verify_native_functional_bank import FLAGS, sha

PREFIX = 'FireSim-generated'
HEADER = '# This file was generated by WriteXDCFile from collected XDCAnnotations.\n'


def audit(directory, *, in_place=False):
    directory = Path(directory)
    path = lambda suffix: directory / (PREFIX + suffix)
    doc = json.loads(path('.native-state-access-constraints.json').read_text())
    bank = json.loads(path('.native-functional-binding.json').read_text())
    root = (re.search(r'(?m)^circuit (\w+) :', (directory/'host.fir').read_text())[1] if in_place else
            json.loads(path('.native-clock-cut.json').read_text())['root_module'])
    circuit_file = directory/'instrumented.fir' if in_place else path('.native-clock-cut.fir')
    annotation_hash = (sha(directory/'instrumented-annotations.json') if in_place else
                       bank['annotation_translation']['translated_sha256'])
    require(set(doc) == {'binding_version', 'scope', 'wrapper_module', 'network_instance', 'network_module',
        'wired_reference_sha256', 'translated_annotations_sha256', 'constraint_specs',
        'original_pre_link_path', 'original_post_link_path', 'rebased_pre_link_path', 'rebased_post_link_path',
        'production_constraints_attached', 'inputs', *FLAGS}, 'changed native constraint binding shape')
    require(doc['binding_version'] == 1 and doc['scope'] == 'native_state_access_constraint_placement_only' and
        doc['wrapper_module'] == root + 'CheckpointStateAccess' and doc['network_module'] == root and
        doc['network_instance'] == 'network' and doc['wired_reference_sha256'] == sha(circuit_file) and
        doc['translated_annotations_sha256'] == annotation_hash and
        doc['production_constraints_attached'] is False and all(doc[k] is v for k, v in FLAGS.items()),
        'changed native constraint identity or admission')
    modules = parse_modules(circuit_file.read_text())
    scopes = {}

    def walk(module, prefix='', ancestors=frozenset()):
        require(module not in ancestors, 'recursive native constraints hierarchy')
        scopes.setdefault(module, []).append(prefix)
        for instance, child in modules[module]['instances'].items():
            walk(child, prefix + instance + '/', ancestors | {module})
    walk(root)

    def target(text):
        match = re.fullmatch(r'~([^|]+)\|([^/>]+)((?:/[^/>]+)*)>([^>]+)', text)
        require(match and match[1] == root and match[2] in scopes, 'foreign/unreachable native constraint target')
        module = match[2]
        relative = []
        for hop in match[3].split('/')[1:]:
            instance, child = hop.split(':')
            require(modules[module]['instances'].get(instance) == child, 'changed native constraint instance hop')
            relative.append(instance)
            module = child
        fields = match[4].split('.')
        require(all(re.fullmatch(r'[A-Za-z_][A-Za-z0-9_$]*', f) for f in fields),
            'unsupported native constraint component')
        owner = modules[module]
        declared = set(owner['ports']) | set(owner['instances']) | owner['aliases']
        declared.update(n for n, _, _ in owner['consumers'])
        declared.update(re.findall(r'^  (?:reg|mem) ([A-Za-z_][A-Za-z0-9_$]*) :', owner['body'], re.M))
        require(fields[0] in declared, 'missing native constraint declaration')
        if len(fields) > 1:
            require(len(fields) == 2 and fields[0] in owner['instances'] and
                fields[1] in modules[owner['instances'][fields[0]]]['ports'], 'missing native constraint public pin')
        return match[2], '/'.join(relative + fields)

    outputs = {}
    target_count = 0
    for destination, phase in (('.synthesis.xdc', 'pre'), ('.implementation.xdc', 'post')):
        original = doc['original_' + phase + '_link_path']
        require(original is None or (isinstance(original, str) and
            all(re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', p) for p in original.split('/'))),
            'invalid native constraint placement')
        rebased = (original + '/' if original is not None else '') + 'network'
        require(doc['rebased_' + phase + '_link_path'] == rebased, 'changed native constraint wrapper placement')
        old_lines, new_lines = [HEADER], [HEADER]
        for spec in doc['constraint_specs']:
            require(set(spec) == {'destination', 'format', 'arguments'} and
                spec['destination'] in ('.synthesis.xdc', '.implementation.xdc'), 'changed native constraint specification')
            if spec['destination'] != destination:
                continue
            pieces = spec['format'].split('{}')
            args = [target(t) for t in spec['arguments']]
            require(len(pieces) == len(args) + 1, 'native constraint argument count')
            require(not args or all(a[0] == args[0][0] for a in args), 'uncorrelated native constraint arguments')
            for prefix in scopes[args[0][0]] if args else ['']:
                target_count += len(args)
                source_placement = ('shell/CL' if phase == 'post' else None) if in_place else original
                for base, lines in ((source_placement, old_lines), (rebased, new_lines)):
                    formatted = [(base + '/' if base is not None else '') + prefix + relative for _, relative in args]
                    lines.append(''.join(piece + (formatted[i] if i < len(formatted) else '')
                        for i, piece in enumerate(pieces)))
        # The unchanged original XDC independently anchors the snippets, their
        # ordering, and all shell-only clauses with no circuit arguments.
        source_xdc = directory/('instrumented'+destination) if in_place else path('.native-clock-cut'+destination)
        require(source_xdc.read_text() == '\n'.join(old_lines),
            'native constraint specs differ from original emitted XDC')
        suffix = '.native-state-access' + destination
        require(path(suffix).read_text() == '\n'.join(new_lines), 'native wrapper constraints differ from reconstruction')
        outputs[suffix] = sha(path(suffix))
    require(doc['inputs'] == outputs, 'missing/changed native wrapper XDC hashes')
    return dict(constraint_specs=len(doc['constraint_specs']), target_arguments=target_count,
        wrapper_module=doc['wrapper_module'], production_constraints_attached=False)
