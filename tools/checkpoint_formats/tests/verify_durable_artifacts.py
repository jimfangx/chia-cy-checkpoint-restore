"""Publication failures using complete production VCS checkpoints/staging."""
import argparse
from contextlib import contextmanager
import errno
import hashlib
import json
import os
from pathlib import Path
import stat
from unittest.mock import patch

from tools.checkpoint_formats import aggregate_packed as packed
from tools.checkpoint_formats.codec import canonical, require
from tools.checkpoint_formats.durable import PublicationError, atomic_output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--production', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    production, out = args.production.resolve(), args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    build, runtime, generated, layout = [json.loads((production/(name+'.json')).read_text())
                                        for name in ('aggregate-build', 'runtime-manifest', 'generated-manifest', 'harness-layout')]
    old_case, new_case = [production/'default'/f'cut-{cut}' for cut in (3, 11)]
    old, new = [(case/'capture.fsckpt').read_bytes() for case in (old_case, new_case)]
    require(old != new, 'publication test requires distinct complete production cuts')
    old_load, new_load = [(case/'aggregate.load').read_bytes() for case in (old_case, new_case)]
    require(old_load != new_load, 'staging test requires distinct complete cuts')
    for data in (old, new):
        packed.decode_aggregate(data, build, runtime, generated, layout)
    real_sync, real_replace = os.fsync, os.replace
    results = []
    for kind in ('container', 'staging'):
        prior, replacement = (old, new) if kind == 'container' else (old_load, new_load)
        def publish(target):
            if kind == 'container':
                return packed.publish_aggregate(new, build, runtime, generated, layout, target)
            return packed.prepare_aggregate_restore(new, build, runtime, generated, layout, target)
        for existing in (False, True):
            for failure in ('write', 'file-sync', 'rename', 'directory-commit'):
                case = out/f'{kind}-{existing}-{failure}'; case.mkdir(exist_ok=True)
                target = case/('capture.fsckpt' if kind == 'container' else 'aggregate.load')
                target.unlink(missing_ok=True)
                if existing:
                    with atomic_output(target, binary=True) as stream:
                        stream.write(prior)
                directory_syncs = 0
                def sync(fd):
                    nonlocal directory_syncs
                    is_directory = stat.S_ISDIR(os.fstat(fd).st_mode)
                    if is_directory: directory_syncs += 1
                    if (failure == 'file-sync' and not is_directory or
                            failure == 'directory-commit' and is_directory and directory_syncs == 2):
                        raise OSError(errno.EIO, 'injected production sync failure')
                    return real_sync(fd)
                def replace(*args, **kwargs):
                    if failure == 'rename':
                        raise OSError(errno.EXDEV, 'injected production rename failure')
                    return real_replace(*args, **kwargs)
                @contextmanager
                def output(destination, *, binary=False):
                    with atomic_output(destination, binary=binary) as stream:
                        class PartialWriter:
                            def write(self, data):
                                # Staging fails in its final section after ALL
                                # native/generated bytes have already been written.
                                if failure == 'write' and (binary or data.startswith('HARNESS ')):
                                    stream.write(data[:max(1, len(data)//2)])
                                    stream.flush()
                                    raise OSError(errno.ENOSPC, 'injected incomplete production write')
                                return stream.write(data)
                        yield PartialWriter()
                with patch('tools.checkpoint_formats.aggregate_packed.atomic_output', output), \
                        patch('tools.checkpoint_formats.durable.os.fsync', side_effect=sync), \
                        patch('tools.checkpoint_formats.durable.os.replace', side_effect=replace):
                    try:
                        publish(target)
                    except PublicationError as error:
                        require(error.published == (failure == 'directory-commit'), 'wrong publication failure status')
                    else:
                        require(False, 'publication failure incorrectly returned success')
                observed = target.read_bytes() if target.exists() else None
                expected = replacement if failure == 'directory-commit' else prior if existing else None
                require(observed == expected, 'partial or unexpected production artifact exposed')
                require(not list(case.glob('.*.pending-*')), 'failed writer left a temporary file')
                results.append(dict(kind=kind, existing=existing, failure=failure,
                                    replacement_visible=failure == 'directory-commit',
                                    observed_bytes=len(observed) if observed else 0,
                                    observed_sha256=hashlib.sha256(observed).hexdigest() if observed else None))
        # A successful replacement must expose exactly the checked artifact.
        target = out/('success.fsckpt' if kind == 'container' else 'success.load')
        publish(target)
        require(target.read_bytes() == replacement, 'successful production replacement differs')
        require(stat.S_IMODE(target.stat().st_mode) == 0o600, 'published file is not private')
    result = dict(failure_cases=results, container_bytes=len(new), staging_bytes=len(new_load),
                  generated_words=sum(e['depth'] for e in generated['state']), native_owners=len(runtime['native_owners']),
                  production_plusargs_enabled=False, physical_fpga_validated=False)
    (out/'summary.json').write_bytes(canonical(result))
    print(f'PASS: {len(results)} full production publication failures; complete container/staging replacements', flush=True)


if __name__ == '__main__': main()
