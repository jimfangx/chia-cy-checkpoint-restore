"""Independent literal RAM_STYLE/retained-memory fixture contract.

No FPGA capture is established here. The same emitted inputs are checked before
native Vivado and fresh EDA VCS, including coherently rehashed corruption.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import tempfile

from tools.checkpoint_formats.codec import require

HEADER = '# This file was generated by WriteXDCFile from collected XDCAnnotations.\n'
FORMAT = 'set_property RAM_STYLE DISTRIBUTED [get_cells -hierarchical -regexp .*{}_reg.*]'
PUBLIC = 'midas.targetutils.xdc.XDCAnnotation'
INTERNAL = 'midas.InternalXDCAnnotation'


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def audit(generated):
    generated = Path(generated)
    binding = json.loads((generated / 'generated-bank-binding.json').read_text())
    for key, name in [('reference_sha256', 'generated-bank-input.fir'),
                      ('instrumented_sha256', 'generated-bank.fir'),
                      ('manifest_sha256', 'generated-bank-semantic.json')]:
        require(binding[key] == sha(generated / name), 'RAM-style unbound circuit/manifest')
    ir = (generated / 'generated-bank.fir').read_text()
    modules = {}
    for side in ('a', 'b'):
        matches = re.findall(r'^    inst ' + side + r' of (\w+)\s*$', ir, re.M)
        require(len(matches) == 1, 'RAM-style missing or duplicate instance')
        modules[side] = matches[0]
    require(len(set(modules.values())) == 2, 'RAM-style aliased physical storage')
    for module in modules.values():
        body = re.search(r'^  module ' + module + r' :.*?(?=^  module |\Z)', ir, re.M | re.S)
        require(body is not None and len(re.findall(r'^    mem ram :', body[0], re.M)) == 1,
                'RAM-style requires the retained logical memory')
    for phase, name in [('source', 'source-annotations.json'), ('translated', 'translated-annotations.json')]:
        annotations = json.loads((generated / name).read_text())
        hints = [a for a in annotations if a.get('class') in (PUBLIC, INTERNAL)]
        required = []
        for side, kind in [('a', PUBLIC), ('b', INTERNAL)]:
            module = 'Leaf' if phase == 'source' else modules[side]
            required.append(dict(**{'class': kind},
                destinationFile={'class': 'midas.targetutils.xdc.XDCFiles$Synthesis$'},
                formatString=FORMAT,
                argumentList=[f'~InitializedStorage|InitializedStorage/{side}:{module}>ram']))
        require(sorted(hints, key=lambda a: a['class']) == sorted(required, key=lambda a: a['class']),
                'RAM-style changed class/destination/format/identity or incomplete hints')
        require(binding['annotation_translation'][phase + '_sha256'] == sha(generated / name),
                'RAM-style unbound annotations')
    synthesis = (generated / 'ram-style.synthesis.xdc').read_text().splitlines()
    require(synthesis[:2] == [HEADER.rstrip('\n'), ''] and sorted(synthesis[2:]) == sorted([
        f'set_property RAM_STYLE DISTRIBUTED [get_cells -hierarchical -regexp .*{side}/ram_reg.*]'
        for side in ('a', 'b')]), 'RAM-style emitted XDC missing/aliased/changed constraint')
    require((generated / 'ram-style.implementation.xdc').read_text() == HEADER,
            'RAM-style wrong downstream destination')
    entries = binding['state']
    require(len(entries) == 2 and {e['hierarchy'] for e in entries} ==
            {'InitializedStorage.a.ram', 'InitializedStorage.b.ram'} and
            all((e['width'], e['depth']) == (9, 8) for e in entries),
            'RAM-style incomplete or reshaped state owners')
    return dict(logical_memories=2, synthesis_constraints=2, public_hints=1, internal_hints=1,
                synthesis_sha256=sha(generated / 'ram-style.synthesis.xdc'))


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--generated', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    out = Path(tempfile.mkdtemp(prefix='ram-style-audit-', dir=args.out)).resolve()
    positive = audit(args.generated)
    rejected = []
    for name in ('missing-xdc', 'retarget-xdc', 'alias-xdc', 'drop-xdc', 'extra-xdc',
                 'wrong-destination', 'drop-hint', 'class-swap', 'changed-style',
                 'retarget-hint', 'drop-owner', 'reshaped-owner'):
        test = out / name
        shutil.copytree(args.generated, test)
        if name == 'missing-xdc':
            (test / 'ram-style.synthesis.xdc').unlink()
        elif name in ('retarget-xdc', 'alias-xdc', 'drop-xdc', 'extra-xdc'):
            f = test / 'ram-style.synthesis.xdc'
            text = f.read_text()
            if name == 'retarget-xdc': text = text.replace('/ram_reg', '/other_reg')
            elif name == 'alias-xdc': text = text.replace('.*b/', '.*a/')
            elif name == 'drop-xdc': text = '\n'.join(text.splitlines()[:2])
            else: text += '\nset_false_path -from [all_clocks]\n'
            f.write_text(text)
        elif name in ('wrong-destination', 'drop-hint', 'class-swap', 'changed-style', 'retarget-hint'):
            f = test / 'translated-annotations.json'
            doc = json.loads(f.read_text())
            hint = next(a for a in doc if a.get('class') == PUBLIC)
            if name == 'wrong-destination': hint['destinationFile']['class'] = 'midas.targetutils.xdc.XDCFiles$Implementation$'
            elif name == 'drop-hint': doc.remove(hint)
            elif name == 'class-swap': hint['class'] = INTERNAL
            elif name == 'changed-style': hint['formatString'] = FORMAT.replace('DISTRIBUTED', 'REGISTERS')
            else: hint['argumentList'][0] = hint['argumentList'][0].replace('>ram', '>clock')
            f.write_text(json.dumps(doc))
            # Updating the producer hash does not discharge the independent
            # memory identity, class, destination and complete constraint oracle.
            b = test / 'generated-bank-binding.json'
            binding = json.loads(b.read_text())
            binding['annotation_translation']['translated_sha256'] = sha(f)
            b.write_text(json.dumps(binding))
        else:
            f = test / 'generated-bank-binding.json'
            doc = json.loads(f.read_text())
            if name == 'drop-owner': doc['state'].pop()
            else: doc['state'][0]['depth'] = 7
            f.write_text(json.dumps(doc))
        try:
            audit(test)
        except (ValueError, FileNotFoundError) as error:
            rejected.append(dict(name=name, error=str(error)))
        else:
            raise AssertionError('accepted RAM-style corruption ' + name)
    receipt = dict(status='pass', scope='component constraint audit only; no FPGA capture',
                   positive=positive, rejected=rejected)
    (out / 'summary.json').write_text(json.dumps(receipt, indent=2) + '\n')
    print(out / 'summary.json')


if __name__ == '__main__':
    main()
