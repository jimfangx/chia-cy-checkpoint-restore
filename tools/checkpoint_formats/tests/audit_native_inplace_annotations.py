"""Independent bounded in-place annotation and real XDC emission audit.

The execution fixture covers correlated parent/descendant constraints, a shared
native leaf and a RAM hint. Unsupported annotation classes reject here rather
than being accepted merely because the Scala translator emitted a hash.
"""
import copy
import hashlib
import json
import re
from pathlib import Path

from tools.checkpoint_formats.codec import canonical, require
from tools.checkpoint_formats.tests.audit_physical_clock_plan import parse_modules
from tools.checkpoint_formats.tests.verify_native_functional_bank import sha

NO_DEDUP = 'firrtl.transforms.NoCircuitDedupAnnotation$'
CACHE = 'firrtl.transforms.CombinationalPath'
XDC = ('midas.InternalXDCAnnotation', 'midas.targetutils.xdc.XDCAnnotation')
HEADER = '# This file was generated by WriteXDCFile from collected XDCAnnotations.\n'


def audit(generated):
    generated = Path(generated)
    load = lambda name: json.loads((generated / name).read_text())
    binding = load('binding.json')
    root = binding['target'].split('|')[0][1:]
    before = parse_modules((generated / 'host.fir').read_text())
    after = parse_modules((generated / 'instrumented.fir').read_text())

    def instances(modules):
        result = {}

        def walk(name, path, seen=()):
            require(name not in seen and path not in result, 'recursive/duplicate annotation execution')
            result[path] = name
            for i, m in modules[name]['instances'].items():
                walk(m, path + '.' + i, seen + (name,))
        walk(root, root)
        return result

    old, new = instances(before), instances(after)
    source = load('host-annotations.json')
    generated_annotations = load('generated-annotations.json')
    actual = load('instrumented-annotations.json')
    projection = load('annotation-projection.json')
    require(projection['projection_version'] == 1 and not projection['complete_fpga_capture'] and
            not projection['deployable_capture_image'], 'changed annotation projection scope')
    for field, name in [('host', 'host'), ('generated', 'generated'), ('instrumented', 'instrumented')]:
        require(projection[field + '_annotations_sha256'] == sha(generated / (name + '-annotations.json')),
                'unbound ' + field + ' annotations')
    require(binding['annotation_projection_sha256'] == sha(generated / 'annotation-projection.json'),
            'unbound annotation projection')

    def target(text, modules, scopes):
        m = re.fullmatch(r'~(\w+)\|(\w+)((?:/\w+:\w+)*)>(\w+)', text)
        require(m is not None and m[1] == root, 'unsupported/foreign annotation target')
        require(m[2] in scopes.values(), 'unreachable annotation root')
        hops = re.findall(r'/(\w+):(\w+)', m[3])
        owner = m[2]
        for instance, child in hops:
            require(modules[owner]['instances'].get(instance) == child, 'stale annotation instance path')
            owner = child
        module = modules[owner]
        require(m[4] in module['ports'] or re.search(r'^  (?:reg|mem|node|wire) ' + re.escape(m[4]) +
                r'(?:\s|\s*:)', module['body'], re.M), 'missing annotation declaration/pin')
        return m[2], hops, m[4]

    def serialized(a):
        kind = a['class']
        if kind == NO_DEDUP:
            return 'NoCircuitDedupAnnotation'
        require(kind in XDC, 'unsupported annotation serialization in bounded audit: ' + kind)
        destination = a['destinationFile']['class'].split('$')[-2]
        return kind.split('.')[-1] + '(' + destination + ',' + a['formatString'] + ',ArraySeq(' + \
            ', '.join(a['argumentList']) + '))'

    expected, mappings = [], []
    for a in source:
        kind = a['class']
        if kind == NO_DEDUP:
            expected.append(a)
            continue
        require(kind in XDC, 'unsupported source annotation in bounded audit: ' + kind)
        args = [target(t, before, old) for t in a['argumentList']]
        require(args and len({t[0] for t in args}) == 1 and a['formatString'].count('{}') == len(args),
                'uncorrelated constraint roots/specifiers')
        copies = []
        executions = sorted(old.items()) if before[args[0][0]]['kind'] == 'extmodule' else old.items()
        for path, module in executions:
            if module != args[0][0]:
                continue
            renamed = []
            for _, hops, ref in args:
                current = path
                if before[module]['kind'] == 'extmodule':
                    # Enumerate original executions, then anchor at the full
                    # circuit root. A local leaf target would also constrain
                    # the newly inserted mask gate in the final hierarchy.
                    text = '~' + root + '|' + new[root]
                    prefix = root
                    for instance in path.split('.')[1:]:
                        prefix += '.' + instance
                        require(prefix in new, 'lost constrained primitive ancestor')
                        text += '/' + instance + ':' + new[prefix]
                else:
                    text = '~' + root + '|' + new[path]
                for instance, _ in hops:
                    current += '.' + instance
                    require(current in new, 'lost constrained execution')
                    text += '/' + instance + ':' + new[current]
                renamed.append(text + '>' + ref)
            a_new = dict(a, argumentList=renamed)
            for t in renamed:
                target(t, after, new)
            copies.append(a_new)
        expected.extend(copies)
        mappings.append(dict(source=serialized(a), targets=[serialized(c) for c in copies]))
    # Annotation JSON is saved in canonical serialize order. Translation keeps
    # the source sequence, which can interleave public/internal XDC classes.
    # Validate every mapping independently, then use that bound sequence for
    # the downstream consumer's order-sensitive output.
    actual_mappings = projection['host_translation']['mappings']
    require(sorted(actual_mappings, key=canonical) == sorted(mappings, key=canonical) and
            projection['host_translation']['translation_version'] == 2,
            'annotation mapping differs from concrete original/new hierarchy')
    require(projection['host_translation']['source_sha256'] == sha(generated / 'host-annotations.json'),
            'translation does not bind the complete fixture source')
    require(projection['invalidated_path_caches'] == [], 'unexpected fixture source cache')
    require(all(a['class'] in (NO_DEDUP, CACHE) for a in generated_annotations),
            'unsupported generated annotation in bounded audit')
    expected.extend(a for a in generated_annotations if a['class'] != CACHE)
    require({canonical(a) for a in actual} == {canonical(a) for a in expected} and
            len(actual) == len({canonical(a) for a in actual}), 'lost/duplicated/changed projected annotation')
    # JsonProtocol's stable, pretty JSON is distinct from the checkpoint codec's
    # canonical JSON. Reconstruct it independently for this bounded class set.
    translated = {canonical(a): a for a in expected}
    text = json.dumps(sorted(translated.values(), key=serialized), indent=2, separators=(',', ':'), ensure_ascii=False)
    require(projection['host_translation']['translated_sha256'] == hashlib.sha256(text.encode()).hexdigest(),
            'changed translated annotation digest')
    caches = [a for a in generated_annotations if a['class'] == CACHE]
    expected_caches = ['CombinationalPath(' + a['sink'] + ',List(' + ', '.join(a['sources']) + '))' for a in caches]
    require(sorted(projection['invalidated_generated_path_caches']) == sorted(expected_caches),
            'unaccounted/changed generated path cache')
    for a in caches:
        target(a['sink'], after, new)
        for t in a['sources']:
            target(t, after, new)

    by_serialized = {serialized(a): a for a in expected}
    emission_order = [by_serialized[t] for m in actual_mappings for t in m['targets']]
    emitted = {'Synthesis': [], 'Implementation': []}
    for a in emission_order:
        if a['class'] not in XDC:
            continue
        args = [target(t, after, new) for t in a['argumentList']]
        destination = a['destinationFile']['class'].split('$')[-2]
        require(destination in emitted, 'unknown XDC destination')
        for path, module in new.items():
            if module != args[0][0]:
                continue
            prefix = ('shell/CL/' if destination == 'Implementation' else '') + path.split('.', 1)[-1].replace('.', '/') + '/'
            if path == root:
                prefix = 'shell/CL/' if destination == 'Implementation' else ''
            values = [prefix + '/'.join([i for i, _ in hops] + [ref]) for _, hops, ref in args]
            pieces = a['formatString'].split('{}')
            emitted[destination].append(''.join(s + (values[i] if i < len(values) else '') for i, s in enumerate(pieces)))
    for name, lines in emitted.items():
        expected_xdc = '\n'.join([HEADER] + lines)
        require((generated / ('instrumented.' + name.lower() + '.xdc')).read_text() == expected_xdc,
                'actual emitted XDC differs from projected concrete paths: ' + name)
    return dict(source_annotations=len(source), projected_annotations=len(actual),
                xdc_lines=sum(map(len, emitted.values())), hierarchy_reconstructed=True)


def corruptions(generated, out):
    import shutil
    out.mkdir(parents=True, exist_ok=True)
    rejected = []
    for name in ('drop-constraint', 'stale-module', 'cross-instance', 'foreign-circuit', 'hidden-pin',
                 'changed-destination', 'changed-format', 'duplicate-constraint', 'xdc-path', 'mapping-loss',
                 'primitive-local-expansion', 'primitive-mask-alias', 'primitive-cross-instance', 'primitive-owner-loss'):
        directory = out / name
        shutil.copytree(generated, directory)
        actual = json.loads((directory / 'instrumented-annotations.json').read_text())
        projection = json.loads((directory / 'annotation-projection.json').read_text())
        xdc = next(a for a in actual if a['class'] in XDC and 'get_pins' in a['formatString'] and
                   any(t.endswith('>CE') for t in a['argumentList']))
        if name == 'drop-constraint': actual.remove(xdc)
        elif name == 'stale-module': xdc['argumentList'][0] = '~NativeHost|Leaf/gate:Native>CE'
        elif name == 'cross-instance':
            a = next(a for a in actual if a['class'] == XDC[0])
            a['argumentList'][1] = '~NativeHost|NativeHost>host_ticks'
        elif name == 'foreign-circuit': xdc['argumentList'][0] = xdc['argumentList'][0].replace('~NativeHost', '~Foreign')
        elif name == 'hidden-pin': xdc['argumentList'][0] = xdc['argumentList'][0].replace('>CE', '>hidden_latch')
        elif name == 'changed-destination': xdc['destinationFile']['class'] = xdc['destinationFile']['class'].replace('Implementation', 'Synthesis')
        elif name == 'changed-format': xdc['formatString'] = 'set_max_delay 999 -to [get_pins {}]'
        elif name == 'duplicate-constraint': actual.append(copy.deepcopy(xdc))
        elif name == 'mapping-loss': projection['host_translation']['mappings'].pop()
        elif name.startswith('primitive-'):
            physical = next(a for a in actual if a['class'] in XDC and a['formatString'].startswith('set_max_delay 9'))
            if name == 'primitive-local-expansion':
                physical['argumentList'] = ['~NativeHost|Native>I', '~NativeHost|Native>O']
            elif name == 'primitive-mask-alias':
                physical['argumentList'] = [
                    '~NativeHost|NativeHost/stage:Stage/network:NativeStorage/checkpoint_physical_root_gate:Native>' + pin
                    for pin in ('I', 'O')]
            elif name == 'primitive-cross-instance':
                other = next(a for a in actual if a is not physical and a['class'] in XDC and
                             a['formatString'].startswith('set_max_delay 9'))
                physical['argumentList'][1] = other['argumentList'][1]
            else:
                actual.remove(physical)
        else:
            p = directory / 'instrumented.implementation.xdc'
            p.write_text(p.read_text().replace('/left_/', '/wrong_instance/'))
        (directory / 'instrumented-annotations.json').write_text(json.dumps(actual))
        projection['instrumented_annotations_sha256'] = sha(directory / 'instrumented-annotations.json')
        (directory / 'annotation-projection.json').write_text(json.dumps(projection))
        binding = json.loads((directory / 'binding.json').read_text())
        binding['annotation_projection_sha256'] = sha(directory / 'annotation-projection.json')
        (directory / 'binding.json').write_text(json.dumps(binding))
        try:
            audit(directory)
        except ValueError as error:
            rejected.append(dict(name='annotation-' + name, error=str(error)))
        else:
            raise ValueError('coherently rehashed annotation corruption accepted: ' + name)
    return rejected
