def main():
    p = argparse.ArgumentParser(__doc__)
    p.add_argument('--generated', type=Path, required=True)
    p.add_argument('--out', type=Path, required=True)
    p.add_argument('--mode', choices=('audit', 'vivado', 'vcs'), default='audit')
    p.add_argument('--models', type=Path)
    args = p.parse_args()
    require(args.generated.resolve().is_relative_to(RUNS) and args.out.resolve().is_relative_to(RUNS), 'evidence must be beneath runs')
    args.out.mkdir(parents=True, exist_ok=True)
    out = Path(tempfile.mkdtemp(prefix='physical-gate-', dir=args.out)).resolve()
    generated = out / 'generated'
    shutil.copytree(args.generated, generated)
    positive = audit(generated)
    # Independently exercise the general complete-instance traversal too.
    inventory = dict(circuit='PhysicalGateTop', root_module='PhysicalGateTop', reference_sha256=sha(generated / 'specialized.fir'),
                     instances=[dict(hierarchy=p, module=m) for p, m in (
                         ('PhysicalGateTop', 'PhysicalGateTop'), ('PhysicalGateTop.left', 'LeftParent'),
                         ('PhysicalGateTop.right', 'RightParent'), ('PhysicalGateTop.left.gate', 'Physical'),
                         ('PhysicalGateTop.right.gate', 'Physical'))])
    manifest = out / 'independent-instance-inventory.json'; manifest.write_text(json.dumps(inventory, indent=2) + '\n')
    positive['external_audit'] = audit_external_owners(generated / 'specialized.fir', manifest, generated / 'external-owners.json')
    for name in SOURCES:
        target = out / 'sources' / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / name, target)
    negatives = []
    for name in ('missing-xdc', 'retarget-xdc', 'cross-instance', 'extra-constraint', 'drop-instance',
                 'metasim-owner', 'claims-capture', 'source-override', 'rename-target', 'gate-polarity',
                 'hidden-port', 'dropped-mapping', 'alias-mapping', 'changed-rtl-clock'):
        test = out / 'negative' / name
        shutil.copytree(generated, test)
        if name == 'missing-xdc': (test / 'physical-gate.implementation.xdc').unlink()
        elif name in ('retarget-xdc', 'cross-instance', 'extra-constraint'):
            f = test / 'physical-gate.implementation.xdc'; text = f.read_text()
            if name == 'retarget-xdc': text = text.replace('/gate/O', '/gate/enable_clk')
            elif name == 'cross-instance': text = text.replace('-source [get_pins left/gate/I]', '-source [get_pins right/gate/I]')
            else: text += '\nset_false_path -from [all_clocks]\n'
            f.write_text(text)
        elif name in ('drop-instance', 'metasim-owner', 'claims-capture', 'source-override'):
            f = test / 'external-owners.json'; doc = json.loads(f.read_text())
            if name == 'drop-instance': doc['reachable_external_instances'].pop()
            elif name == 'metasim-owner': doc['reachable_external_instances'][0]['physical_contract']['state'] = 'O'
            elif name == 'claims-capture': doc['complete_fpga_capture'] = True
            else: doc['reachable_external_instances'][0]['inline_sources'] = [dict(filename='BUFGCE.v')]
            f.write_text(json.dumps(doc))
        elif name == 'rename-target':
            f = test / 'annotations.json'; f.write_text(f.read_text().replace('RightParent/gate', 'LeftParent/gate'))
        elif name in ('gate-polarity', 'hidden-port'):
            f = test / 'specialized.fir'; text = f.read_text()
            text += '\n    parameter IS_CE_INVERTED = 1\n' if name == 'gate-polarity' else '\n    output hidden : UInt<1>\n'
            f.write_text(text)
        elif name in ('dropped-mapping', 'alias-mapping'):
            f = test / 'mappings.json'; doc = json.loads(f.read_text())
            if name == 'dropped-mapping': doc['mappings'].pop()
            else: doc['mappings'][0]['targets'][1] = doc['mappings'][0]['targets'][0]
            f.write_text(json.dumps(doc))
        else:
            f = test / 'specialized.sv'; f.write_text(f.read_text().replace('posedge gate_O', 'posedge clock'))
        try:
            audit(test)
        except (ValueError, FileNotFoundError) as e:
            negatives.append(dict(name=name, error=str(e)))
        else:
            raise AssertionError('accepted physical gate corruption ' + name)
    commands = []

    def run(argv, log, cwd=out, expected=0):
        row = dict(argv=[str(a) for a in argv], cwd=str(cwd), log=str(out / log))
        commands.append(row)
        with (out / log).open('w') as stream:
            r = subprocess.run(row['argv'], cwd=cwd, stdout=stream, stderr=subprocess.STDOUT)
        row['returncode'] = r.returncode
        (out / 'commands.json').write_text(json.dumps(commands, indent=2) + '\n')
        require(r.returncode == expected, 'physical gate tool failed: ' + str(out / log))
        return (out / log).read_text()

    models = None
    if args.mode == 'vivado':
        (out / 'synth.tcl').write_text(TCL)
        text = run(['vivado', '-mode', 'batch', '-source', 'synth.tcl', '-log', 'vivado.log', '-journal', 'vivado.jou'], 'synth.log')
        require('PHYSICAL_GATE_SYNTH_PASS gates=2 registers=16 constraints=6' in text, 'missing native synthesis checks')
        require(not re.search(r'(?:CRITICAL WARNING|WARNING|ERROR): \[Constraints ', text), 'unresolved physical constraints')
        with zipfile.ZipFile(out / 'physical-gate.dcp') as archive:
            require(archive.testzip() is None, 'invalid physical checkpoint')
            xdc = '\n'.join(archive.read(n).decode() for n in archive.namelist() if n.endswith('.xdc'))
            for side in ('left', 'right'):
                require(side + '/gate' in xdc and 'ck_' + side + '/gate/O' in xdc, 'DCP lost native clock constraint')
    if args.mode == 'vcs':
        require(os.environ.get('VCS_HOME') == toolchain.VCS_HOME, 'run on EDA with vcs-env.sh sourced last')
        require(args.models and args.models.resolve().is_relative_to(RUNS), 'supply native model snapshot under runs')
        models = json.loads((args.models / 'model-origins.json').read_text())
        for name in ('BUFGCE.v', 'glbl.v'):
            require(sha(args.models / name) == models['files'][name]['sha256'], 'unbound native model')
            shutil.copyfile(args.models / name, out / name)
        shutil.copyfile(args.models / 'model-origins.json', out / 'model-origins.json')
        (out / 'reference.sv').write_text((generated / 'reference.sv').read_text().replace('module PhysicalGateTop(', 'module PhysicalGateReference('))
        (out / 'tb.sv').write_text(TB)
        run([toolchain.VCS, '-full64', '-sverilog', '-timescale=1ns/1ps', '-Mupdate', '-debug_access+all',
             '-top', 'physical_gate_tb', '-top', 'glbl', '-o', 'simv', generated / 'specialized.sv',
             'reference.sv', 'BUFGCE.v', 'glbl.v', 'tb.sv', out / 'sources' / SOURCES[-1]], 'compile.log')
        healthy = out / 'healthy'; healthy.mkdir()
        text = run([out / 'simv', '-no_save'], 'healthy.log', healthy)
        require('PHYSICAL_GATE_PASS checks=4064 source_edges=512' in text, 'missing public-boundary equivalence')
        corrupt = out / 'corrupt'; corrupt.mkdir()
        text = run([out / 'simv', '-no_save', '+corrupt'], 'corrupt.log', corrupt, expected=1)
        require('PHYSICAL_GATE_DIVERGENCE source_edge=4' in text and 'PHYSICAL_GATE_PASS' not in text, 'corruption did not stop at first check')
        require(all((out / n / 'physical-gate.vcd').stat().st_size > 100 for n in ('healthy', 'corrupt')), 'missing debug waveforms')
    receipt = dict(status='pass', backend='eda' if args.mode == 'vcs' else 'f2', mode=args.mode,
                   observed_utc=datetime.now(timezone.utc).isoformat(), host=socket.gethostname(), original_root=str(ROOT),
                   scope='physical clock constraint/compiler component only', physical_fpga_capture=False,
                   full_rocket_image_build=False, positive=positive, negatives=negatives, commands=commands,
                   generated={n: sha(generated / n) for n in NAMES}, sources={n: sha(out / 'sources' / n) for n in SOURCES},
                   model_origins=models,
                   artifacts={str(f.relative_to(out)): sha(f) for f in out.rglob('*') if f.is_file() and
                              f.suffix in ('.log', '.vcd', '.dcp', '.rpt', '.v', '.sv', '.tcl')})
    (out / 'summary.json').write_text(json.dumps(receipt, indent=2) + '\n')
    print(out / 'summary.json')


if __name__ == '__main__':
    main()
