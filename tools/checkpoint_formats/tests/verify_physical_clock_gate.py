CELL = 'set_property DONT_TOUCH true [get_cells {}]'
CLOCK = 'create_generated_clock -name ck_{} -source [get_pins {}] -divide_by 1 [get_pins {}]'
DELAY = 'set_max_delay 7.0 -from [get_pins {}]'
HEADER = '# This file was generated by WriteXDCFile from collected XDCAnnotations.'
PRIMITIVE = '''extmodule Physical :
    input I : Clock
    input CE : UInt<1>
    output O : Clock
    defname = BUFGCE'''


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def annotation(kind, file, fmt, targets):
    return dict(**{'class': kind}, destinationFile={'class': f'midas.targetutils.xdc.XDCFiles${file}$'},
                formatString=fmt, argumentList=['~PhysicalGateTop|' + t for t in targets])


def audit(generated):
    """Literal fixture oracle, independent of Scala's admission/rename helpers."""
    generated = Path(generated)
    for name in NAMES:
        require((generated / name).is_file(), 'missing physical constraint input ' + name)
    before = [annotation('midas.InternalXDCAnnotation', 'Synthesis', CELL, ['Parent>gate']),
              annotation('midas.InternalXDCAnnotation', 'Implementation', CLOCK, ['Physical>O', 'Physical>I', 'Physical>O']),
              annotation('midas.targetutils.xdc.XDCAnnotation', 'Implementation', DELAY, ['Parent/gate:Physical>O'])]
    after = [annotation('midas.InternalXDCAnnotation', 'Synthesis', CELL, [m + '>gate']) for m in ('LeftParent', 'RightParent')]
    after += [annotation('midas.InternalXDCAnnotation', 'Implementation', CLOCK,
                         [f'PhysicalGateTop/{s}:{m}/gate:Physical>{pin}' for pin in ('O', 'I', 'O')])
              for s, m in (('left', 'LeftParent'), ('right', 'RightParent'))]
    after += [annotation('midas.targetutils.xdc.XDCAnnotation', 'Implementation', DELAY,
                         [m + '/gate:Physical>O']) for m in ('LeftParent', 'RightParent')]
    after += [{'class': 'firrtl.transforms.NoCircuitDedupAnnotation$'}]
    require(json.loads((generated / 'input-annotations.json').read_text()) == before, 'changed source constraint')
    require(json.loads((generated / 'annotations.json').read_text()) == after, 'changed translated constraint')
    expected_lines = {
        'synthesis': [f'set_property DONT_TOUCH true [get_cells {s}/gate]' for s in ('left', 'right')],
        'implementation': [f'create_generated_clock -name ck_{s}/gate/O -source [get_pins {s}/gate/I] -divide_by 1 [get_pins {s}/gate/O]' for s in ('left', 'right')]
        + [f'set_max_delay 7.0 -from [get_pins {s}/gate/O]' for s in ('left', 'right')]}
    for suffix, expected in expected_lines.items():
        body = (generated / f'physical-gate.{suffix}.xdc').read_text()
        require(body.splitlines()[0] == HEADER and sorted(x for x in body.splitlines() if x and not x.startswith('#')) == sorted(expected),
                'changed emitted physical constraints: ' + suffix)
    fir = (generated / 'specialized.fir').read_text()
    require(fir.count('extmodule ') == 1 and fir.split('  extmodule ')[1].strip() == PRIMITIVE[len('extmodule '):],
            'physical primitive definition changed')
    require(re.findall(r'^  module (\w+) :', fir, re.M) == ['PhysicalGateTop', 'LeftParent', 'RightParent'], 'changed clone modules')
    for side, module in [('left', 'LeftParent'), ('right', 'RightParent')]:
        require(f'inst {side} of {module}' in fir, 'changed concrete hierarchy')
    require(fir.count('inst gate of Physical') == 2 and fir.count('reg saved : UInt<8>, gate.O') == 2,
            'lost physical clock or storage owner')
    require(fir.count('gate.I <= clock') == fir.count('gate.CE <= ce') == 2, 'altered physical clock wiring')
    # Check emitted RTL as well; a coherent report cannot conceal a new source
    # implementation, parameter override or a replacement clock connection.
    rtl = (generated / 'specialized.sv').read_text()
    require(len(re.findall(r'\bBUFGCE gate \(', rtl)) == 2 and 'module BUFGCE' not in rtl and
            'BUFGCE #' not in rtl and rtl.count('.O(gate_O)') == 2 and
            rtl.count('always @(posedge gate_O)') == 2, 'emitted native primitive/clock changed')
    doc = json.loads((generated / 'external-owners.json').read_text())
    definition_hash = hashlib.sha256(PRIMITIVE.replace('\n    ', '\n  ').encode()).hexdigest()
    # FIRRTL serializes a definition at indent zero without a final newline.
    contract = dict(contract='xilinx-bufgce-default-sync-v1', definition_sha256=definition_hash,
                    ce_type='SYNC', input_inverted=False, enable_inverted=False,
                    state='transparent_low_ce_latch', public_pins=['I', 'CE', 'O'],
                    direct_state_readout=False, physical_capture_binding='unsupported',
                    required_cut='common_host_low_phase_all_owners_with_enable_latch_mapping',
                    metasim_state_equivalent=False)
    rows = [dict(hierarchy='PhysicalGateTop.' + s + '.gate', module='Physical', defname='BUFGCE',
                 definition_sha256=definition_hash, inline_sources=[], physical_primitive=True,
                 physical_capture_binding='unsupported', requires_explicit_owner=True, physical_contract=contract)
            for s in ('left', 'right')]
    expected = dict(audit_version=1, scope='external_owner_admission_only', root_module='PhysicalGateTop',
                    reference_sha256=sha(generated / 'specialized.fir'), deployable_capture_image=False,
                    complete_fpga_capture=False, reachable_external_instances=rows, unused_external_definitions=[])
    require(doc == expected, 'changed physical state/constraint contract')
    mapping = json.loads((generated / 'mappings.json').read_text())
    require(set(mapping) == {'translation_version', 'source_sha256', 'translated_sha256', 'mappings'} and
            mapping['translation_version'] == 2 and len(mapping['mappings']) == 3, 'invalid translation provenance')
    def serialized(a):
        kind = a['class'].split('.')[-1].rstrip('$')
        if 'formatString' not in a:
            return kind
        file = a['destinationFile']['class'].split('$')[-2]
        return kind + '(' + file + ',' + a['formatString'] + ',ArraySeq(' + ', '.join(a['argumentList']) + '))'
    def annotation_hash(values):
        text = json.dumps(sorted(values, key=serialized), indent=2, separators=(',', ':'), ensure_ascii=False)
        return hashlib.sha256(text.encode()).hexdigest()
    require(mapping['source_sha256'] == annotation_hash(before) and mapping['translated_sha256'] == annotation_hash(after),
            'unbound physical annotation translation')
    expected_mappings = [dict(source=serialized(a), targets=[serialized(t) for t in targets])
                         for a, targets in zip(before, (after[:2], after[2:4], after[4:6]))]
    require(mapping['mappings'] == expected_mappings, 'missing changed or aliased physical translation')
    return dict(physical_instances=2, independently_checked_constraints=6, capture_owner_supported=False)


TB = r'''`timescale 1ns/1ps
module physical_gate_tb;
  import "DPI-C" function void checkpoint_network_fail();
  reg clock = 0, ce_left = 1, ce_right = 1;
  reg [7:0] data = 0;
  wire [7:0] a, b, ref_a, ref_b;
  PhysicalGateTop dut (.clock(clock), .ce_left(ce_left), .ce_right(ce_right), .data(data), .a(a), .b(b));
  PhysicalGateReference reference (.clock(clock), .ce_left(ce_left), .ce_right(ce_right), .data(data), .a(ref_a), .b(ref_b));
  integer checks = 0, cycle = 0;
  reg corrupt;
  task fail;
    begin
      $display("PHYSICAL_GATE_DIVERGENCE source_edge=%0d", cycle);
      checkpoint_network_fail();
      $fatal(1, "failure status helper returned");
    end
  endtask
  task compare;
    begin
      if (cycle >= 4) begin
        if (corrupt && cycle == 4) begin
          if (a !== (ref_a ^ 8'h1)) fail();
        end else if ({a,b} !== {ref_a,ref_b} || $isunknown({a,b}))
          fail();
        checks = checks + 2;
      end
    end
  endtask
  initial begin
    corrupt = $test$plusargs("corrupt");
    $dumpfile("physical-gate.vcd"); $dumpvars(0, physical_gate_tb);
    #150;
    for (cycle = 0; cycle < 512; cycle = cycle + 1) begin
      clock = 0;
      ce_left = cycle < 4 || cycle % 3 != 0;
      ce_right = cycle < 4 || cycle % 5 != 0;
      data = cycle * 17 + cycle / 5;
      #3; compare();
      clock = 1; #3; compare();
      ce_left = !ce_left; ce_right = !ce_right;
      #3; compare();
      clock = 0; #3; compare();
    end
    $display("PHYSICAL_GATE_PASS checks=%0d source_edges=512", checks); $finish;
  end
endmodule
'''

